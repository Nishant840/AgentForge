import uuid
from datetime import datetime
from enum import Enum
from sqlalchemy import String, DateTime, Text, ForeignKey, Enum as SAEnum
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.dialects.postgresql import UUID
from apps.api.core.database import Base

class TaskStatus(str, Enum):
    """Enumeration of possible execution states for an autonomous task."""
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"

class Task(Base):
    """Database model representing an autonomous agent task assigned to a repository."""
    __tablename__ = "tasks"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )

    repository_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("repositories.id", ondelete="CASCADE"),  # Cascade delete tasks if the parent repository is removed
        nullable=False
    )

    description: Mapped[str] = mapped_column(
        Text, nullable=False  # Natural language instruction provided by the user (e.g., "Fix auth bug")
    )

    status: Mapped[TaskStatus] = mapped_column(
        SAEnum(TaskStatus), nullable=False, default=TaskStatus.PENDING
    )

    result: Mapped[str | None] = mapped_column(
        Text, nullable=True  # Final output or summary generated by the agent upon completion
    )

    error_message: Mapped[str | None] = mapped_column(
        Text, nullable=True  # Error details captured if the task execution fails
    )

    steps_log: Mapped[str | None] = mapped_column(
        Text, nullable=True  # Serialized JSON string recording every step and thought of the agent
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, default=datetime.utcnow
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, default=datetime.utcnow, onupdate=datetime.utcnow
    )

    def __repr__(self) -> str:
        return f"<Task {self.id} [{self.status}]>"